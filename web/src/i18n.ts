export type MessageKey = keyof typeof en
const messages: Record<Locale, Messages> = { en, 'zh-TW': zhTWMessages }

const STORAGE_KEY = 'rsagent.locale'

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'zh-TW') return saved
  } catch {
    // 隐私模式等情况下读不到，退回浏览器语言
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-TW' : 'en'
}

export const locale = ref<Locale>(initialLocale())

watch(
  locale,
  (l) => {
    document.documentElement.lang = l
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      // 忽略
    }
  },
  { immediate: true },
)

export const localeOptions = [
  { label: 'English', value: 'en' },
  { label: '正體中文', value: 'zh-TW' },
]

/** 取译文，{name} 占位符用 params 替换。 */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let s = messages[locale.value][key] ?? en[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** 有译文时取译文，否则原样返回（用于后端传来的状态名）。 */
export function tOr(key: string, fallback: string): string {
  return (messages[locale.value] as Record<string, string>)[key] ?? fallback
}

/** 供 toLocaleString 使用的 BCP 47 标签。 */
export const dateTag = computed(() => (locale.value === 'en' ? 'en-US' : 'zh-TW'))

export function formatTime(v: string | number | Date): string {
  return new Date(v).toLocaleString(dateTag.value, { hour12: false })
}

export const naiveLocale = computed(() => (locale.value === 'en' ? enUS : zhTW))
export const naiveDateLocale = computed(() => (locale.value === 'en' ? dateEnUS : dateZhTW))
