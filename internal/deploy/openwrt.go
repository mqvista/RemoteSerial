package deploy

// OpenWrt 的系统服务：procd 管理的 /etc/init.d/rsagent。
//
// 不用 kardianos/service 的 procd 支持：它的脚本在网络之后、tailscale 之前启动（START=21），
// 服务名是 RemoteSerialAgent，而且脚本已存在时安装会失败（套件会自带脚本）。

import (
	"context"
	"encoding/json"
	"os"
	"os/exec"
	"strings"
	"time"

	"rsagent/internal/i18n"
	"rsagent/internal/platform"
)

const (
	// ProcdInitScript 是 OpenWrt 上的服务脚本。
	ProcdInitScript = "/etc/init.d/rsagent"
	// OpenWrtBinary 是 OpenWrt 上服务使用的程序（套件也装在这里）。
	OpenWrtBinary = "/usr/bin/rsagent"
	procdName     = "rsagent"
)

// procdRun 执行命令，测试时替换。
var procdRun = func(name string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
	return string(out), err
}

// ProcdScript 生成 /etc/init.d/rsagent。START=99 让它排在网络与 tailscale 之后启动；
// respawn 的重试次数为 0 表示无限重启。
func ProcdScript(o Options) string {
	args := []string{OpenWrtBinary, "service", "run"}
	if o.DataDir != "" {
		args = append(args, "--data-dir", o.DataDir)
	}
	if o.Listen != "" {
		args = append(args, "--listen", o.Listen)
	}
	for i, a := range args {
		args[i] = shq(a)
	}
	return `#!/bin/sh /etc/rc.common
# RemoteSerial Agent (rsagent): serial-to-TCP bridge over Tailscale.
# Generated by "rsagent service install"; running it again rewrites this file.

USE_PROCD=1
START=99
STOP=10

start_service() {
	procd_open_instance
	procd_set_param command ` + strings.Join(args, " ") + `
	procd_set_param respawn 3600 5 0
	procd_set_param stdout 1
	procd_set_param stderr 1
	procd_set_param term_timeout 30
	procd_close_instance
}
`
}

// shq 给 shell 参数加单引号；只含安全字符时原样返回，脚本更易读。
func shq(s string) string {
	safe := s != ""
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("/._-:=@+,", r)) {
			safe = false
			break
		}
	}
	if safe {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func openwrtServiceStatus(o Options) ServiceStatus {
	st := ServiceStatus{Supported: true, Manager: "procd", Binary: OpenWrtBinary, Packaged: platform.PackageInstalled(procdName)}
	if _, err := os.Stat(ProcdInitScript); err != nil {
		return st
	}
	st.Installed = true
	_, err := procdRun(ProcdInitScript, "enabled")
	st.Enabled = err == nil
	st.Running = procdRunning()
	return st
}

// procdRunning 通过 ubus 查询服务实例是否在运行。
func procdRunning() bool {
	out, err := procdRun("ubus", "call", "service", "list", `{"name":"`+procdName+`"}`)
	if err != nil {
		return false
	}
	return parseProcdRunning(out)
}

func parseProcdRunning(out string) bool {
	var v map[string]struct {
		Instances map[string]struct {
			Running bool `json:"running"`
		} `json:"instances"`
	}
	if json.Unmarshal([]byte(out), &v) != nil {
		return false
	}
	for _, inst := range v[procdName].Instances {
		if inst.Running {
			return true
		}
	}
	return false
}

func openwrtServiceAction(o Options, action string) error {
	if !isElevated() {
		return i18n.New("需要 root 权限")
	}
	script := func(op string) error {
		if out, err := procdRun(ProcdInitScript, op); err != nil {
			return i18n.Errorf("%s %s 失败: %w", ProcdInitScript, op, withOutput(err, out))
		}
		return nil
	}
	switch action {
	case ActionServiceInstall:
		if !sameFile(o.ExePath, OpenWrtBinary) {
			if err := copyBinary(o.ExePath, OpenWrtBinary); err != nil {
				return i18n.Errorf("复制程序到 %s: %w", OpenWrtBinary, err)
			}
		}
		want := ProcdScript(o)
		if cur, err := os.ReadFile(ProcdInitScript); err != nil || string(cur) != want {
			if err := os.WriteFile(ProcdInitScript, []byte(want), 0o755); err != nil {
				return i18n.Errorf("写入 %s: %w", ProcdInitScript, err)
			}
		}
		if err := script("enable"); err != nil {
			return err
		}
		if procdRunning() {
			return script("restart")
		}
		return script("start")
	case ActionServiceRemove:
		_ = script("stop")
		_ = script("disable")
		// 套件安装的脚本留给套件管理器卸载
		if platform.PackageInstalled(procdName) == "" {
			if err := os.Remove(ProcdInitScript); err != nil && !os.IsNotExist(err) {
				return i18n.Errorf("删除 %s: %w", ProcdInitScript, err)
			}
		}
		return nil
	case ActionServiceStart:
		return script("start")
	case ActionServiceStop:
		return script("stop")
	case ActionServiceRestart:
		return script("restart")
	}
	return i18n.Errorf("未知服务动作 %q", action)
}

type outputError struct {
	err error
	out string
}

func (e *outputError) Error() string { return e.err.Error() + ": " + e.out }
func (e *outputError) Unwrap() error { return e.err }

func withOutput(err error, out string) error {
	out = strings.TrimSpace(out)
	if out == "" {
		return err
	}
	return &outputError{err: err, out: out}
}
