package systs

import (
	"context"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"strings"

	"rsagent/internal/i18n"
)

// 系统 tailscaled 的代理：OpenWrt 的服务脚本没有代理选项，所以在 /etc/init.d/tailscale 的
// procd_close_instance 前插一行，载入 rsagent 生成的 proxyEnvFile（procd_append_param env …）。
// tailscale 套件升级会覆盖服务脚本，SyncProxy 定期检查并补回。

// 测试时替换。
var proxyEnvFile = "/etc/rsagent/tailscaled-proxy.sh"

const proxyHookMark = "# rsagent-proxy"

func proxyHookLine() string {
	return "  [ -f " + proxyEnvFile + " ] && . " + proxyEnvFile + " " + proxyHookMark
}

// proxyEnvContent 生成 proxyEnvFile 的内容；u 为 nil 返回空。
func proxyEnvContent(u *url.URL) string {
	if u == nil {
		return ""
	}
	s := u.String()
	var vars []string
	if u.Scheme == "http" || u.Scheme == "https" {
		vars = []string{"HTTPS_PROXY=" + s, "HTTP_PROXY=" + s}
	} else {
		vars = []string{"ALL_PROXY=" + s}
	}
	vars = append(vars, "NO_PROXY=localhost,127.0.0.1,::1")
	var b strings.Builder
	b.WriteString("# Generated by rsagent (Settings -> Proxy). Do not edit.\n")
	b.WriteString("procd_append_param env")
	for _, v := range vars {
		b.WriteString(" " + shellQuote(v))
	}
	b.WriteString("\n")
	return b.String()
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// SyncProxy 让系统 tailscaled 使用 u 作代理（u 为 nil 表示不用），需要时重启 tailscaled。
// 返回是否做了改动。没有服务脚本时什么也不做。
func SyncProxy(ctx context.Context, out io.Writer, u *url.URL) (bool, error) {
	data, err := os.ReadFile(initScript)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	script := string(data)
	want := proxyEnvContent(u)
	have, _ := os.ReadFile(proxyEnvFile)
	hooked := strings.Contains(script, proxyHookMark)

	changed := false
	if want == "" {
		if hooked {
			if err := writeAtomic(initScript, removeHook(script), 0o755); err != nil {
				return false, err
			}
			changed = true
		}
		if len(have) > 0 {
			if err := os.Remove(proxyEnvFile); err != nil && !os.IsNotExist(err) {
				return changed, err
			}
			changed = true
		}
	} else {
		if string(have) != want {
			if err := os.MkdirAll(filepath.Dir(proxyEnvFile), 0o700); err != nil {
				return false, err
			}
			if err := writeAtomic(proxyEnvFile, []byte(want), 0o600); err != nil {
				return false, err
			}
			changed = true
		}
		if !hooked {
			patched, ok := addHook(script)
			if !ok {
				return changed, i18n.Errorf("无法在 %s 中加入代理设置（找不到 procd_close_instance）", initScript)
			}
			if err := writeAtomic(initScript, patched, 0o755); err != nil {
				return changed, err
			}
			changed = true
		}
	}
	if !changed {
		return false, nil
	}
	if !processRunning("tailscaled") {
		return true, nil
	}
	step(out, i18n.T("重新启动 tailscale 以套用代理设置"))
	if err := Runner(ctx, out, initScript, "restart"); err != nil {
		return true, i18n.Errorf("重新启动 tailscale 失败: %w", err)
	}
	return true, nil
}

// ProxyHooked 报告服务脚本当前是否带有代理设置。
func ProxyHooked() bool {
	data, err := os.ReadFile(initScript)
	if err != nil || !strings.Contains(string(data), proxyHookMark) {
		return false
	}
	fi, err := os.Stat(proxyEnvFile)
	return err == nil && fi.Size() > 0
}

func addHook(script string) ([]byte, bool) {
	lines := strings.Split(script, "\n")
	for i, l := range lines {
		if strings.TrimSpace(l) == "procd_close_instance" {
			out := append([]string{}, lines[:i]...)
			out = append(out, proxyHookLine())
			out = append(out, lines[i:]...)
			return []byte(strings.Join(out, "\n")), true
		}
	}
	return nil, false
}

func removeHook(script string) []byte {
	lines := strings.Split(script, "\n")
	out := lines[:0]
	for _, l := range lines {
		if !strings.Contains(l, proxyHookMark) {
			out = append(out, l)
		}
	}
	return []byte(strings.Join(out, "\n"))
}

func writeAtomic(path string, data []byte, mode os.FileMode) error {
	tmp := path + ".rsagent-tmp"
	if err := os.WriteFile(tmp, data, mode); err != nil {
		return err
	}
	if err := os.Chmod(tmp, mode); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}
